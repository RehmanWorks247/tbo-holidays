type TranslatedTuple<T extends readonly string[]> = { [K in keyof T]: string };

export interface PageValues {
  home: TranslatedTuple<typeof homePaths>;
  booking: TranslatedTuple<typeof bookingPaths>;
  results: TranslatedTuple<typeof resultsPaths>;
  app: TranslatedTuple<typeof appPaths>;
}

export function createPageMessages(values: PageValues): PageMessages {
  const result: Record<string, unknown> = {};
  const sections = { home: homePaths, booking: bookingPaths, results: resultsPaths, app: appPaths };
  for (const section of Object.keys(sections) as (keyof PageValues)[]) {
    const branch: Record<string, unknown> = {};
    result[section] = branch;
    sections[section].forEach((path, index) => {
      const keys = path.split('.');
      let target = branch;
      for (const key of keys.slice(0, -1)) {
        const child = target[key] ?? {};
        target[key] = child;
        target = child as Record<string, unknown>;
      }
      target[keys[keys.length - 1]!] = values[section][index];
    });
  }
  return result as PageMessages;
}
