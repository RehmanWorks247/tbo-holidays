type Strings<T extends readonly unknown[]> = { readonly [Index in keyof T]: string };
type Translation = {
  [Section in keyof typeof sectionKeys]: Strings<(typeof sectionKeys)[Section]>;
};
type Branch = { [key: string]: string | Branch };

function pageMessages(copy: Translation): PageMessages {
  const result: Branch = {};
  for (const section of Object.keys(sectionKeys) as (keyof typeof sectionKeys)[]) {
    const paths = sectionKeys[section];
    const values = copy[section];
    paths.forEach((path, index) => {
      const value = values[index];
      if (typeof value !== 'string' || !value.trim()) throw new Error('Missing page translation');
      const parts = path.split('.');
      const leaf = parts.pop()!;
      let branch = result;
      for (const part of parts) {
        const existing = branch[part];
        if (typeof existing === 'string') throw new Error('Invalid page translation path');
        branch = existing ?? (branch[part] = {});
      }
      branch[leaf] = value;
    });
  }
  return result as unknown as PageMessages;
}

